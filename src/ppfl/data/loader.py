def load_raw_dataset(cfg: Config, raw_dir: Path | None = None) -> RawDataset:
    """Load the dataset named in ``cfg.data.dataset`` from ``raw_dir``."""
    dataset = canonical_dataset_name(cfg.data.dataset)
    raw_dir = Path(raw_dir) if raw_dir is not None else cfg.raw_dir
    if dataset == "synthetic":
        from ppfl.data.synthetic import generate_synthetic_traffic

        frame = generate_synthetic_traffic(cfg.data.synthetic, derive_seed(cfg.experiment.seed, "synthetic"))
        raw_dir.mkdir(parents=True, exist_ok=True)
        frame.to_csv(raw_dir / "synthetic_iot.csv", index=False)
        features = [c for c in frame.columns if c not in META_COLS]
        return RawDataset(frame, features, [str(raw_dir / "synthetic_iot.csv")])
    if not raw_dir.exists():
        raise FileNotFoundError(f"Raw data directory {raw_dir} does not exist (see data/README.md)")
    if dataset == "nbaiot":
        return load_nbaiot(raw_dir, cfg)
    return load_tabular(raw_dir, cfg, dataset)


PROCESSED_FILE = "cleaned.parquet"
METADATA_FILE = "metadata.json"


def save_processed(frame: pd.DataFrame, metadata: dict[str, Any], out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    frame.to_parquet(out_dir / PROCESSED_FILE, index=False)
    save_json(metadata, out_dir / METADATA_FILE)


def load_processed(out_dir: Path) -> tuple[pd.DataFrame, dict[str, Any]]:
    path = out_dir / PROCESSED_FILE
    if not path.exists():
        raise FileNotFoundError(
            f"Processed dataset not found at {path}. Run `python scripts/prepare_data.py "
            f"--dataset {out_dir.name}` first (or `--synthetic` for the test dataset)."
        )
    frame = pd.read_parquet(path)
    metadata = load_json(out_dir / METADATA_FILE) if (out_dir / METADATA_FILE).exists() else {}
    return frame, metadata
